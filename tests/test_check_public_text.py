"""tools/check_public_text.py: one author of record, no co-author trailer or AI-tool footer."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "tools" / "check_public_text.py"


def run(
    *args: str, stdin: str | None = None, cwd: Path | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        input=stdin,
        capture_output=True,
        text=True,
        encoding="utf-8",
        cwd=cwd,
    )


def body(text: str) -> subprocess.CompletedProcess[str]:
    return run("--stdin", stdin=text)


def message(text: str, tmp_path: Path) -> subprocess.CompletedProcess[str]:
    msg = tmp_path / "COMMIT_EDITMSG"
    msg.write_text(text, encoding="utf-8")
    return run("--message-file", str(msg))


ATTRIBUTION_LINES = [
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "co-authored-by: A Person <a@example.com>",
    "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated by Claude",
    "Made with Cursor",
    "Generated with GitHub Copilot",
    "Built with Claude Code",
    "Assisted-by: Claude Code",
    "Generated-by: Claude",
    "Generated with Claude Opus 4.5",
    "Generated with [Claude Code](https://claude.ai/code) by Anthropic",
    "Drafted with Claude Code.",
    "Authored by Claude.",
    "Generated with gpt-5",
    "Co-authored-by : A Person <a@example.com>",
    "This PR was generated with Claude Code.",
]


@pytest.mark.parametrize("line", ATTRIBUTION_LINES)
def test_attribution_in_a_pr_body_fails(line: str) -> None:
    result = body(f"Fix the origin guard.\n\n{line}\n")
    assert result.returncode == 1
    assert "attribution" in result.stdout


@pytest.mark.parametrize("line", ATTRIBUTION_LINES)
def test_attribution_in_a_commit_message_fails(line: str, tmp_path: Path) -> None:
    result = message(f"Fix the origin guard\n\n{line}\n", tmp_path)
    assert result.returncode == 1
    assert "attribution" in result.stdout


@pytest.mark.parametrize("opener", ["```\n", "> "])
def test_an_unclosed_fence_or_a_quote_does_not_hide_a_trailer(opener: str, tmp_path: Path) -> None:
    text = f"Fix the origin guard\n\n{opener}Co-Authored-By: Claude <noreply@anthropic.com>\n"
    assert message(text, tmp_path).returncode == 1


def test_other_trailers_still_pass(tmp_path: Path) -> None:
    msg = "Fix the origin guard\n\nSigned-off-by: dependabot[bot] <support@github.com>\nRefs: #39\n"
    assert message(msg, tmp_path).returncode == 0


def test_quoting_the_rule_in_a_code_span_passes() -> None:
    assert body("The trailer `Co-Authored-By: Claude` is refused.\n").returncode == 0


@pytest.mark.parametrize(
    "text",
    [
        "They were generated with the same code as the first 7.",
        "The narrative is generated by OpenAI, with Anthropic as the fallback.",
        "generated by OpenAI, with Anthropic as the fallback.",
        "Reviewed-by: A Person <a@example.com>",
        "Signed-off-by: Jane <jane@cursor.example>",
        "Narratives generated by Claude Code sessions are checked by the guard.",
        "The narrative is generated by OpenAI.",
    ],
)
def test_ordinary_prose_about_tools_passes(text: str) -> None:
    assert body(text + "\n").returncode == 0


def test_base_mode_checks_each_commit_on_the_branch(tmp_path: Path) -> None:
    def git(*args: str) -> None:
        subprocess.run(
            ["git", "-c", "commit.gpgsign=false", *args],
            cwd=tmp_path,
            check=True,
            capture_output=True,
        )

    git("init", "-q", "-b", "main")
    git("config", "user.name", "Owner")
    git("config", "user.email", "owner@example.com")
    git("commit", "-q", "--allow-empty", "-m", "Start")
    git("switch", "-q", "-c", "topic")
    git(
        "commit",
        "-q",
        "--allow-empty",
        "-m",
        "Fix the guard\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
    )
    result = run("--base", "main", cwd=tmp_path)
    assert result.returncode == 1
    assert "attribution" in result.stdout
