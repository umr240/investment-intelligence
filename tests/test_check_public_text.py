"""tools/check_public_text.py: dashes, person and AI-tool attribution."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "tools" / "check_public_text.py"


def check(text: str, *args: str, tmp_path: Path | None = None) -> subprocess.CompletedProcess[str]:
    if args == ("--message-file",):
        assert tmp_path is not None
        msg = tmp_path / "COMMIT_EDITMSG"
        msg.write_text(text, encoding="utf-8")
        argv = [sys.executable, str(SCRIPT), "--message-file", str(msg)]
        return subprocess.run(argv, capture_output=True, text=True)
    argv = [sys.executable, str(SCRIPT), "--stdin"]
    return subprocess.run(argv, input=text, capture_output=True, text=True)


ATTRIBUTION_LINES = [
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "co-authored-by: Claude <claude@example.com>",
    "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated by Claude",
]


@pytest.mark.parametrize("line", ATTRIBUTION_LINES)
def test_attribution_in_a_pr_body_fails(line: str) -> None:
    result = check(f"Fix the origin guard.\n\n{line}\n")
    assert result.returncode == 1
    assert "AI attribution" in result.stdout


@pytest.mark.parametrize("line", ATTRIBUTION_LINES[:2])
def test_attribution_trailer_in_a_commit_message_fails(line: str, tmp_path: Path) -> None:
    result = check(f"Fix the origin guard\n\n{line}\n", "--message-file", tmp_path=tmp_path)
    assert result.returncode == 1
    assert "AI attribution" in result.stdout


def test_other_trailers_still_pass(tmp_path: Path) -> None:
    msg = "Fix the origin guard\n\nCo-Authored-By: A Person <a@example.com>\nRefs: #39\n"
    assert check(msg, "--message-file", tmp_path=tmp_path).returncode == 0


def test_quoting_the_rule_in_a_code_span_passes() -> None:
    assert check("The trailer `Co-Authored-By: Claude` is refused.\n").returncode == 0


def test_ordinary_use_of_generated_passes() -> None:
    assert check("They were generated with the same code as the first 7.\n").returncode == 0
